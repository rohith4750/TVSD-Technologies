// Generates 1,000+ realistic audit logs for TanStack Virtual demonstration
export function generateVirtualAuditLogs(count: number = 2000): AuditLogRecord[] {
  const actors = [
    { name: 'Alexander Wright', email: 'alexander.w@tvsd.io' },
    { name: 'Sarah Chen, MD', email: 'sarah.chen@tvsd.io' },
    { name: 'Marcus Vance', email: 'marcus.v@tvsd.io' },
    { name: 'Elena Rostova', email: 'elena.r@tvsd.io' },
    { name: 'Automated Worker #4', email: 'system@tvsd.io' },
  ];

  const actions = [
    'USER_AUTHENTICATED',
    'ORDER_STATUS_CHANGED',
    'PRODUCT_STOCK_ADJUSTED',
    'INVOICE_GENERATED',
    'PERMISSION_UPDATED',
    'THEME_PREFERENCE_SYNCED',
    'LAYOUT_ENGINE_SWITCH',
    'DATA_EXPORT_CSV',
  ];

  const modules = ['Auth', 'Orders', 'Inventory', 'Billing', 'Security', 'Themes', 'Core'];

  const logs: AuditLogRecord[] = [];
  const baseTime = Date.now();

  for (let i = 1; i <= count; i++) {
    const actor = actors[i % actors.length];
    const action = actions[i % actions.length];
    const mod = modules[i % modules.length];
    const isError = i % 23 === 0;
    const isWarning = i % 11 === 0 && !isError;

    logs.push({
      id: `audit-${i.toString().padStart(5, '0')}`,
      timestamp: new Date(baseTime - i * 145000).toISOString(),
      actor: actor.name,
      actorEmail: actor.email,
      action,
      module: mod,
      ipAddress: `192.168.${(i % 10) + 1}.${(i % 254) + 1}`,
      status: isError ? 'FAILURE' : isWarning ? 'WARNING' : 'SUCCESS',
      details: `${action} executed successfully by ${actor.name} on module [${mod}]. Session trace ID: #sec-tx-${i * 19}`,
    });
  }

  return logs;
}
